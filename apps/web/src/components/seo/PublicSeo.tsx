import { useEffect } from "react";
import { useLocation } from "react-router-dom";

const SITE_URL = "https://www.nuqaa-asir.com";

type SeoConfig = {
  title: string;
  description: string;
  indexable: boolean;
};

const PUBLIC_SEO: Record<string, SeoConfig> = {
  "/": {
    title: "نقاء عسير لخدمات التنظيف | أبها وخميس مشيط",
    description:
      "خدمات تنظيف منزلية وتجارية موثوقة في أبها وخميس مشيط. تنظيف منازل وشقق ومكاتب ومفروشات وخزانات، بفريق مدرب وحجز إلكتروني سهل.",
    indexable: true,
  },
  "/services": {
    title: "خدمات التنظيف في أبها وخميس مشيط | نقاء عسير",
    description:
      "استعرض خدمات تنظيف المنازل والشقق والمكاتب والمفروشات والخزانات وما بعد البناء في أبها وخميس مشيط.",
    indexable: true,
  },
  "/service-areas": {
    title: "مناطق خدمة نقاء عسير | أبها وخميس مشيط",
    description:
      "تعرف على مناطق خدمة نقاء عسير ورسوم التنقل لخدمات التنظيف في أبها وخميس مشيط ومنطقة عسير.",
    indexable: true,
  },
  "/faq": {
    title: "الأسئلة الشائعة عن خدمات التنظيف | نقاء عسير",
    description:
      "إجابات عن الحجز والأسعار والمواعيد وخدمات التنظيف التي تقدمها نقاء عسير في أبها وخميس مشيط.",
    indexable: true,
  },
};

function setMeta(selector: string, attribute: "content" | "href", value: string) {
  const element = document.head.querySelector<HTMLElement>(selector);
  element?.setAttribute(attribute, value);
}

/** Keeps metadata accurate after client-side navigation. Build-time HTML for
 * the four public landing pages is generated by scripts/prerender-static.mjs.
 */
export function PublicSeo() {
  const { pathname } = useLocation();

  useEffect(() => {
    const serviceDetail = pathname.startsWith("/services/");
    const config =
      PUBLIC_SEO[pathname] ??
      (serviceDetail
        ? {
            title: "تفاصيل خدمة التنظيف | نقاء عسير",
            description: "تفاصيل وأسعار وحجز خدمات نقاء عسير للتنظيف في أبها وخميس مشيط.",
            indexable: true,
          }
        : {
            title: "نقاء عسير لخدمات التنظيف",
            description: "بوابة عملاء نقاء عسير لخدمات التنظيف.",
            indexable: false,
          });

    const canonicalPath = pathname === "/" ? "/" : pathname.replace(/\/+$/, "");
    const canonicalUrl = `${SITE_URL}${canonicalPath}`;

    document.title = config.title;
    setMeta('meta[name="description"]', "content", config.description);
    setMeta(
      'meta[name="robots"]',
      "content",
      config.indexable
        ? "index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1"
        : "noindex, nofollow",
    );
    setMeta('link[rel="canonical"]', "href", canonicalUrl);
    setMeta('meta[property="og:title"]', "content", config.title);
    setMeta('meta[property="og:description"]', "content", config.description);
    setMeta('meta[property="og:url"]', "content", canonicalUrl);
    setMeta('meta[name="twitter:title"]', "content", config.title);
    setMeta('meta[name="twitter:description"]', "content", config.description);
  }, [pathname]);

  return null;
}
